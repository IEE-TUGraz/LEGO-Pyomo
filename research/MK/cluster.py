def _tm_variant(spec: str) -> tuple[str, list[str]]:
    """'base' | 'shift:N' | 'perturb:R' -> (label used in task keys, Markov.py arguments)."""
    if spec == "base":
        return "base", []
    kind, _, value = spec.partition(":")
    if kind == "shift":
        return f"shiftTM{int(value)}", ["--shift-tm", str(int(value))]
    if kind == "perturb":
        return f"perturbTM{float(value):g}", ["--perturb-tm", value]
    raise ValueError(f"Unknown tm variant '{spec}' (use 'base', 'shift:N' or 'perturb:R')")


def _tm_entry(entry) -> tuple[str, list[str], set[float] | None, bool]:
    """grid.tm entry: 'spec' or {spec, stretch_demand = [...] (only these demand levels), low_priority = bool}
    -> (label, Markov.py arguments, allowed stretch_demand values or None = all, low priority)."""
    if isinstance(entry, str):
        return *_tm_variant(entry), None, False
    unknown = set(entry) - {"spec", "stretch_demand", "low_priority"}
    if unknown or "spec" not in entry:
        raise ValueError(f"grid.tm entry {entry}: needs 'spec', optional 'stretch_demand' and 'low_priority' (unknown: {sorted(unknown)})")
    sds = {float(s) for s in entry["stretch_demand"]} if "stretch_demand" in entry else None
    return *_tm_variant(entry["spec"]), sds, bool(entry.get("low_priority", False))


def _resources(cfg: dict, res_class: str, dataset: str) -> dict:
    """[resources.<class>] default, overridden by its <dataset> entry; truth-original falls back to the 'full' class."""
    res_cfg = cfg["resources"]
    if res_class not in res_cfg and res_class == "truth-original":
        res_class = "full"
    section = res_cfg[res_class]
    flat = {k: v for k, v in section.items() if not isinstance(v, dict)}
    res = {**section.get("default", {}), **flat, **section.get(dataset, {})}
    missing = {"cpus", "mem", "time"} - res.keys()
    if missing:
        raise ValueError(f"[resources.{res_class}] for '{dataset}' lacks {sorted(missing)}")
    return {"cpus": int(res["cpus"]), "mem": str(res["mem"]), "time": str(res["time"])}


def _dataset_codes(datasets: list[str]) -> dict:
    """{dataset folder name: 2-character job-name code} (first two letters/digits, upper case), unique per run."""
    codes = {}
    for dataset in datasets:
        name = Path(dataset).name
        codes[name] = re.sub(r"[^A-Za-z0-9]", "", name)[:2].upper().ljust(2, "X")
    clashes = {c for c in codes.values() if list(codes.values()).count(c) > 1}
    if clashes:
        raise ValueError(f"grid.datasets: job-name codes {sorted(clashes)} are not unique ({codes}) - rename a dataset folder "
                         f"or extend _dataset_codes")
    return codes


def build_plan(cfg: dict) -> dict:
    """All tasks of the config: {key: {key, group, index, cmd, res, deps}}. Tasks of one group (= one job array) share
    task kind, edge handling and dataset (hence resources); within a dataset every grid point has the same index in
    all its groups, so array dependencies can use aftercorr (task i waits for task i)."""
    grid, markov = cfg["grid"], cfg.get("markov", {})
    tasks = sorted(grid["tasks"], key=GRID_TASKS.index)
    for task in tasks:
        for dep_task, _ in TASK_DEPS[task]:
            if dep_task not in tasks:
                raise ValueError(f"grid.tasks: '{task}' needs '{dep_task}'")
    edges = grid["edges"]
    tms = [_tm_entry(t) for t in grid["tm"]]
    stretch = [float(s) for s in grid.get("stretch_demand", [1.0])]
    for label, _, sds, _ in tms:
        if sds is not None and not sds <= set(stretch):
            raise ValueError(f"grid.tm '{label}': stretch_demand {sorted(sds - set(stretch))} not in grid.stretch_demand")
    clusters = [int(c) for c in grid["clusters"]]

    solver_args = ["--threads", "@THREADS@"]
    if markov.get("node_file_start") is not None and markov.get("node_file_start_fraction") is not None:
        raise ValueError("[markov]: set either node_file_start or node_file_start_fraction, not both")
    if markov.get("node_file_start") is not None:
        solver_args += ["--node-file-start", str(markov["node_file_start"]), "--node-file-dir", "@NODEDIR@"]
    elif markov.get("node_file_start_fraction") is not None:
        if not 0 < float(markov["node_file_start_fraction"]) <= 1:
            raise ValueError("[markov] node_file_start_fraction must be in (0, 1]")
        solver_args += ["--node-file-start", "@NODEFILESTART@", "--node-file-dir", "@NODEDIR@"]  # set by the job script

    def markov_cmd(dataset, sd, *extra):
        cmd = ["python", "research/MK/Markov.py", dataset, "--reuse-inputfiles", "--no-overwrite", "--debug", *markov.get("args", [])]
        if sd != 1.0:
            cmd += ["--stretch-demand", f"{sd:g}"]
        return cmd + list(extra)

    plan = {}
    ds_codes = _dataset_codes(grid["datasets"])
    rank = {name: i for i, name in enumerate(ds_codes)}  # scheduling preference among the own jobs = grid.datasets order

    def add(key, group, index, cmd, res, deps, dataset=None, task=None, edge=None, low=False):
        bad = [a for a in cmd if re.search(r"[\s'\"\\]", a)]
        if bad:
            raise ValueError(f"Arguments must not contain whitespace or quotes (the job script splits on whitespace): {bad}")
        # Low-priority tasks: lower-case dataset code (tells their arrays apart in squeue), ranked after all datasets
        code = ds_codes.get(dataset, "")
        jobname = group if dataset is None else f"{code.lower() if low else code}{TASK_CODES[task]}{EDGE_CODES.get(edge, edge and edge[:2])}_{group}"
        task_rank = rank.get(dataset, 0) + (len(rank) if low else 0)  # evaluate (no dataset): 0
        plan[key] = {"key": key, "group": group, "jobname": jobname, "rank": task_rank, "index": index, "cmd": " ".join(cmd), "res": res, "deps": deps}

    for dataset in grid["datasets"]:
        name = Path(dataset).name
        for si, sd in enumerate(stretch, 1):
            prefix = f"{name}/sd{sd:g}"
            add(f"{prefix}/prepare", f"prepare-{name}", si,
                markov_cmd(dataset, sd, "--clusters", ",".join(map(str, clusters)), "--prepare-only"),
                _resources(cfg, "prepare", name), [], name, "prepare")
            if grid.get("truth_original", False):
                add(f"{prefix}/truth-original", f"truth-original-{name}", si, markov_cmd(dataset, sd, *solver_args, "--task", "truth-original"),
                    _resources(cfg, "truth-original", name), [f"{prefix}/prepare"], name, "truth-original")

        # Grid points longest first: high cluster counts, then the TM variants in config order (base first). Low-priority
        # TM variants form their own job arrays (one --nice per array) with their own index sequence.
        points = sorted(((si, c, ti) for si, c, ti in itertools.product(range(len(stretch)), clusters, range(len(tms)))
                         if tms[ti][2] is None or stretch[si] in tms[ti][2]), key=lambda p: (-p[1], p[2], p[0]))
        for low in (False, True):
            for gi, (si, c, ti) in enumerate([p for p in points if tms[p[2]][3] == low], 1):
                sd, (tm_label, tm_args, _, _) = stretch[si], tms[ti]
                prefix = f"{name}/sd{sd:g}/c{c}/{tm_label}"
                for task in tasks:
                    if task in ORIGINAL_TASKS and tm_label != "base":
                        continue
                    for edge in (["Truth"] if task in TRUTH_TASKS else []) + edges:
                        deps = [f"{prefix}/{t}/{edge if e == 'EDGE' else e}" for t, e in TASK_DEPS[task]] or [f"{name}/sd{sd:g}/prepare"]
                        res_class = "rp" if task in ("main", "operational") and edge != "Truth" else "full"
                        add(f"{prefix}/{task}/{edge}", f"{task}-{edge}-{name}" + ("-low" if low else ""), gi,
                            markov_cmd(dataset, sd, *solver_args, "--clusters", str(c), *tm_args, "--task", task, "--edge", edge),
                            _resources(cfg, res_class, name), deps, name, task, edge, low)

    # Work units / solver times are compared between edge handlings and Truth: all solves of a dataset need the same threads
    for dataset in grid["datasets"]:
        name = Path(dataset).name
        cpus = {t["res"]["cpus"] for t in plan.values() if t["key"].startswith(f"{name}/") and not t["key"].endswith("/prepare")}
        if len(cpus) > 1:
            raise ValueError(f"[resources]: the solves of '{name}' use different cpus {sorted(cpus)} - set the same cpus for rp, full "
                             f"and truth-original, otherwise work units and solver times are not comparable")

    evaluate = cfg.get("evaluate")
    if evaluate is not None:
        cmd = ["python", "research/MK/EvaluateMarkov.py", *evaluate.get("args", ["all", "--no-show"])]
        if evaluate.get("output_dir"):
            cmd += ["--output-dir", evaluate["output_dir"]]
        add("evaluate", "evaluate", 1, cmd, _resources(cfg, "evaluate", "evaluate"), [])

    # squeue shows 8 characters of the job name: they must tell the job arrays apart
    heads = {}
    for t in plan.values():
        heads.setdefault(t["jobname"][:8], set()).add(t["group"])
    clashes = {h: sorted(g) for h, g in heads.items() if len(g) > 1}
    if clashes:
        raise ValueError(f"Job names not distinguishable by their first 8 characters: {clashes} - extend TASK_CODES/EDGE_CODES")
    return plan


def group_tasks(plan: dict) -> dict:
    """{group: [task, ...]} in plan (= dependency) order."""
    groups = {}
    for task in plan.values():
        groups.setdefault(task["group"], []).append(task)
    return groups


def group_dependency(plan: dict, members: list) -> str | None:
    """Slurm --dependency of a job array: aftercorr on parent groups whose task i the task i depends on, afterok on
    whole parent groups otherwise (prepare). Parent groups are referenced as '@group' and resolved at submission."""
    same_index = {}  # parent group -> every dependency into it has the dependent task's own index
    for task in members:
        for dep in task["deps"]:
            parent = plan[dep]
            same_index[parent["group"]] = same_index.get(parent["group"], True) and parent["index"] == task["index"]
    corr = [g for g, same in same_index.items() if same]
    whole = [g for g, same in same_index.items() if not same]
    parts = ([f"aftercorr:{':'.join('@' + g for g in corr)}"] if corr else []) + ([f"afterok:{':'.join('@' + g for g in whole)}"] if whole else [])
    return ",".join(parts) or None


def compress_indices(indices: list[int]) -> str:
    """[1, 2, 3, 7] -> '1-3,7'."""
    out = []
    for _, run in itertools.groupby(enumerate(sorted(indices)), lambda p: p[1] - p[0]):
        run = [i for _, i in run]
        out.append(f"{run[0]}-{run[-1]}" if len(run) > 1 else str(run[0]))
    return ",".join(out)


