def run_dir(name_or_config: str) -> Path:
    path = Path(name_or_config)
    name = tomllib.loads(path.read_text())["name"] if path.is_file() else name_or_config
    return RUNS_DIR / name


def load_state(name_or_config: str) -> tuple[Path, dict]:
    rdir = run_dir(name_or_config)
    if not (rdir / "state.json").exists():
        sys.exit(f"No submitted run in '{rdir}' (submit it first)")
    return rdir, json.loads((rdir / "state.json").read_text())


def save_state(rdir: Path, state: dict) -> None:
    tmp = rdir / "state.json.tmp"
    tmp.write_text(json.dumps(state, indent=1))
    tmp.replace(rdir / "state.json")


def _now() -> str:
    return datetime.datetime.now().isoformat(timespec="seconds")


def current_job(task: dict) -> str | None:
    return task["attempts"][-1]["job"] if task["attempts"] else None


def nice(task: dict, step: int) -> int:
    """sbatch --nice of a task: rank (grid.datasets order, low-priority TM variants after all datasets) x nice_step. A positive
    nice is the only way to order the own jobs without operator rights; it costs the same against other users' jobs."""
    return task.get("rank", 0) * step


def _nice_step(value) -> int:
    step = int(value)
    if step < 0:
        sys.exit("nice_step must be >= 0 (a negative nice needs operator rights)")
    return step


def prioritize(state: dict, keys, slurm: "Slurm") -> None:
    """Re-apply the nice of the given (queued) tasks' jobs, e.g. after changing nice_step. Array jobs go in by array id."""
    nice_jobs = {}
    for key in keys:
        job = current_job(state["tasks"][key])
        job = job and job.split("_")[0]
        jobs = nice_jobs.setdefault(nice(state["tasks"][key], state.get("nice_step", DEFAULT_NICE_STEP)), [])
        if job and job not in jobs:
            jobs.append(job)
    if not nice_jobs:
        print("No queued jobs")
        return
    print(f"Setting the nice of {sum(map(len, nice_jobs.values()))} queued job(s) / array(s): "
          + ", ".join(f"{len(j)} x {n}" for n, j in sorted(nice_jobs.items())))
    slurm.renice(nice_jobs)


def classify(state: dict, info: dict) -> dict:
    """{key: (category, slurm info)}. A task whose job is pending on a dependency that can never be satisfied, or that
    was cancelled while an ancestor failed, counts as blocked."""
    result = {}
    for key, task in state["tasks"].items():
        job = current_job(task)
        entry = info.get(job, {}) if job else {}
        st = entry.get("state", "")
        if st == "COMPLETED":
            cat = DONE
        elif st in _RUNNING_STATES:
            cat = RUNNING
        elif st == "PENDING":
            cat = BLOCKED if "DependencyNeverSatisfied" in entry.get("reason", "") else PENDING
        elif st in _FAILED_STATES:
            cat = FAILED
        else:
            cat = UNKNOWN
        result[key] = [cat, entry]
    for key in state["tasks"]:  # cancelled because of a failed ancestor -> blocked (kill_invalid_depend clusters)
        if result[key][0] == FAILED and result[key][1].get("state") == "CANCELLED" and failed_ancestors(state, result, key):
            result[key][0] = BLOCKED
    return result


def failed_ancestors(state: dict, status: dict, key: str) -> list[str]:
    found, stack, seen = [], list(state["tasks"][key]["deps"]), set()
    while stack:
        dep = stack.pop()
        if dep in seen:
            continue
        seen.add(dep)
        if status[dep][0] == FAILED and status[dep][1].get("state") != "CANCELLED":
            found.append(dep)
        else:
            stack.extend(state["tasks"][dep]["deps"])
    return found


def descendants(state: dict, keys: set[str]) -> list[str]:
    """All tasks depending (transitively) on keys, in plan order (excluding keys and evaluate)."""
    children = {}
    for key, task in state["tasks"].items():
        for dep in task["deps"]:
            children.setdefault(dep, []).append(key)
    found, stack = set(), list(keys)
    while stack:
        for child in children.get(stack.pop(), []):
            if child not in found and child not in keys:
                found.add(child)
                stack.append(child)
    return [k for k in state["tasks"] if k in found]


