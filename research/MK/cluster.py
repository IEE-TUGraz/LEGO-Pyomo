class Slurm:
    def __init__(self, dry_run: bool = False):
        self.dry_run = dry_run
        self._dry_id = 0

    def sbatch(self, args: list[str]) -> str:
        cmd = ["sbatch", "--parsable", *args]
        if self.dry_run:
            self._dry_id += 1
            print("  " + " ".join(cmd))
            return f"DRY{self._dry_id}"
        out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout.strip()
        return out.split(";")[0]

    def scancel(self, job_ids: list[str]) -> None:
        if not job_ids:
            return
        if self.dry_run:
            print("  scancel " + " ".join(job_ids))
            return
        for i in range(0, len(job_ids), 200):
            subprocess.run(["scancel", *job_ids[i:i + 200]], check=False)

    def renice(self, nice_jobs: dict[int, list[str]]) -> None:
        """scontrol update Nice of queued jobs, {nice: [job id, ...]} (an array id covers the array's pending tasks)."""
        for nice, job_ids in nice_jobs.items():
            for i in range(0, len(job_ids), 200):
                cmd = ["scontrol", "update", f"JobId={','.join(job_ids[i:i + 200])}", f"Nice={nice}"]
                if self.dry_run:
                    print("  " + " ".join(cmd))
                    continue
                out = subprocess.run(cmd, capture_output=True, text=True)
                if out.returncode != 0:
                    print(f"  warning: setting Nice={nice} failed ({(out.stderr or out.stdout).strip()})")

    @staticmethod
    def query(job_ids: set[str]) -> dict:
        """{job id ('A_i' or 'J'): {state, reason, exit, elapsed, maxrss_mb, reqmem}} from squeue (queued/running,
        array tasks expanded) and sacct (everything that started)."""
        info = {}
        parents = sorted({j.split("_")[0] for j in job_ids if not j.startswith("DRY")})
        if not parents:
            return info
        for i in range(0, len(parents), 200):
            out = subprocess.run(["sacct", "-n", "-P", "-j", ",".join(parents[i:i + 200]),
                                  "--format=JobID,State,ExitCode,Elapsed,MaxRSS,ReqMem"], capture_output=True, text=True).stdout
            for line in out.splitlines():
                job, state, exit_code, elapsed, maxrss, reqmem = (line.split("|") + [""] * 6)[:6]
                if "[" in job:
                    continue  # still-pending part of an array: squeue has the expanded tasks
                base, _, step = job.partition(".")
                entry = info.setdefault(base, {})
                if step:
                    rss = _mem_mb(maxrss)
                    if rss is not None:
                        entry["maxrss_mb"] = max(entry.get("maxrss_mb", 0), rss)
                else:
                    entry.update(state=state.split()[0], exit=exit_code, elapsed=elapsed, reqmem=reqmem)
        user = os.environ.get("USER", "")
        out = subprocess.run(["squeue", "-h", "-r", "-u", user, "-o", "%i|%T|%r"], capture_output=True, text=True).stdout
        for line in out.splitlines():
            job, state, reason = (line.split("|") + ["", ""])[:3]
            if job.split("_")[0] in parents:
                info.setdefault(job, {}).update(state=state, reason=reason)
        return info


def _mem_mb(value: str) -> float | None:
    m = re.fullmatch(r"([\d.]+)([KMGT]?)n?c?", value.strip())
    if not m:
        return None
    return float(m.group(1)) * {"": 1 / 1024 ** 2, "K": 1 / 1024, "M": 1, "G": 1024, "T": 1024 ** 2}[m.group(2)]


def _fmt_mem(mb: float) -> str:
    return f"{mb / 1024:.0f}G" if mb >= 10 * 1024 else f"{mb:.0f}M"


def _scale_mem(mem: str, factor: float) -> str:
    return _fmt_mem(_mem_mb(mem.upper().removesuffix("B")) * factor)


