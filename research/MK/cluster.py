def _load_config(name_or_config: str) -> tuple[Path, dict]:
    """(TOML path, config) from a TOML file, or a run name resolved to experiments/<name>.toml."""
    path = Path(name_or_config)
    if not path.is_file():
        path = HERE / "experiments" / f"{name_or_config}.toml"
    if not path.is_file():
        sys.exit(f"No config '{name_or_config}' (give a TOML file or the name of one in {HERE / 'experiments'})")
    return path.resolve(), tomllib.loads(path.read_text())


def estimate_levels(key: str) -> list[str]:
    """Estimate levels of a task, most specific first: the task itself, then the same task / edge with the same RP count,
    the same task / edge, and the resource class - all within its dataset (demand level and TM are ignored)."""
    parts = key.split("/")
    if parts[-1] in ("prepare", "truth-original") and len(parts) >= 2:
        return [key, f"{parts[0]}/{parts[-1]}"]
    if len(parts) != 6:  # evaluate (or an unknown key format): only its own measurements
        return [key]
    dataset, clusters, task, edge = parts[0], parts[2], parts[-2], parts[-1]
    return [key, f"{dataset}/{task}/{edge}/{clusters}", f"{dataset}/{task}/{edge}", f"{dataset}/class:{resource_class(key)}"]


def pool_specs(plan: dict, keys: list[str]) -> dict:
    """pool.Worker specs of the given tasks (plan order = dependency order); `python` becomes this interpreter."""
    specs = {}
    for key in keys:
        task = plan[key]
        cmd = task["cmd"].split(" ")
        specs[key] = {"cmd": [sys.executable, *cmd[1:]] if cmd[0] == "python" else cmd, "deps": task["deps"], "cpus": task["res"]["cpus"],
                      "prior_mem_mb": _mem_mb(task["res"]["mem"].upper().removesuffix("B")), "prior_time_s": _elapsed_s(task["res"]["time"]) or 0,
                      "rank": task.get("rank", 0), "dataset_rank": task.get("dataset_rank", 0), "low": task.get("low", False),
                      "after_all": key == "evaluate"}  # evaluate: after all others (like afterany)
    return specs


def select_keys(plan: dict, patterns: list[str], with_deps: bool = False) -> list[str]:
    selected = {k for k in plan if any(fnmatch.fnmatch(k, p) for p in patterns)}
    if not selected:
        sys.exit(f"No task matches {patterns} (task keys look like 'TX-123BT/sd1/prepare', see README)")
    if with_deps:
        stack = list(selected)
        while stack:
            for dep in plan[stack.pop()]["deps"]:
                if dep not in selected:
                    selected.add(dep)
                    stack.append(dep)
    return [k for k in plan if k in selected]


def seed_records(cfg: dict) -> list[dict]:
    """Measurements of this run and of [pool] seed_runs: runs/<run>/measurements.json (Slurm runs, `resources --save`)
    and runs/<run>/pool/results/ (pool runs)."""
    records = []
    for run in dict.fromkeys([cfg["name"], *cfg.get("pool", {}).get("seed_runs", [])]):
        rdir = RUNS_DIR / run
        if (rdir / "measurements.json").exists():
            records += [{**r, "source": f"slurm:{run}"} for r in json.loads((rdir / "measurements.json").read_text())]
        if (rdir / "pool" / "results").is_dir() and run != cfg["name"]:  # the own pool is read by the worker itself
            records += [{**r, "source": f"pool:{run}"} for r in pool.Store(rdir / "pool").results()]
    return records


def _slurm_end_time() -> float | None:
    """End of the current Slurm job (start + time limit) as a timestamp, if running inside one."""
    job = os.environ.get("SLURM_JOB_ID")
    if not job:
        return None
    out = subprocess.run(["squeue", "-h", "-j", job, "-o", "%e"], capture_output=True, text=True).stdout.strip()
    try:
        return datetime.datetime.fromisoformat(out).timestamp()
    except ValueError:
        return None


def make_worker(cfg: dict, specs: dict, store: "pool.Store", *, cores: int, mem_mb: float, **kwargs) -> "pool.Worker":
    pcfg = cfg.get("pool", {})
    estimator = pool.Estimator(specs, estimate_levels, mem_safety=float(pcfg.get("mem_safety", 1.2)),
                               time_safety=float(pcfg.get("time_safety", 1.5)), time_level=lambda level: "/class:" not in level)
    kwargs.setdefault("mem_fraction", float(pcfg.get("mem_fraction", 0.9)))
    kwargs.setdefault("disk_min_free_mb", float(pcfg.get("disk_min_free_gb", DEFAULT_DISK_MIN_FREE_GB)) * 1024)
    if pcfg.get("rank_offset_hours") is not None:  # soft dataset order; absent = strict (grid.datasets order first)
        kwargs.setdefault("rank_offset_s", float(pcfg["rank_offset_hours"]) * 3600)
    return pool.Worker(specs, store, estimator, cwd=HERE.parent.parent, cores=cores, mem_mb=mem_mb, seed_records=seed_records(cfg), **kwargs)


def _parse_mem_arg(value: str | None, name: str) -> float | None:
    if value is None:
        return None
    mb = _mem_mb(value.upper().removesuffix("B"))
    if mb is None:
        sys.exit(f"{name} '{value}': use e.g. 700G or 16000M")
    return mb


def cmd_worker(args) -> None:
    """Run the shared pool of a config on this machine (a Slurm node or any other machine with access to the repo)."""
    config_path, cfg = _load_config(args.config)
    plan = build_plan(cfg)
    keys = select_keys(plan, args.patterns or ["*"])
    rdir = RUNS_DIR / cfg["name"]
    if (rdir / "state.json").exists():
        sys.exit(f"'{rdir}' holds a per-task Slurm run (state.json) - use a different run name for the pool")
    store = pool.Store(rdir / "pool")
    meta = store.root / "meta.json"
    if not meta.exists():
        pool._write_json_atomic(meta, {"config": str(config_path), "created": _now()})
    total, _ = pool.machine_memory_mb()
    mem_mb = _parse_mem_arg(args.mem, "--mem") or total
    if mem_mb is None:
        sys.exit("Cannot determine this machine's memory - pass --mem")
    end_time = time.time() + args.hours * 3600 if args.hours else _slurm_end_time()
    idle_h = args.idle_hours if args.idle_hours is not None else float(cfg.get("pool", {}).get("idle_hours", DEFAULT_IDLE_HOURS))
    chain = None
    if args.chain_script:
        def chain():
            job = _sbatch_from_job(args.chain_script)
            if job:
                store.add_job(job, {"submitted_by": os.environ.get("SLURM_JOB_ID") or "local", "script": args.chain_script})
            return job
    worker = make_worker(cfg, pool_specs(plan, keys), store, cores=args.cores or os.cpu_count() or 1, mem_mb=mem_mb,
                         end_time=end_time, idle_s=idle_h * 3600, max_tasks=args.max_tasks, node_base=args.node_dir,
                         chain_after_s=args.chain_after_hours * 3600 if args.chain_script else None, chain=chain)
    sys.exit(worker.run())


def _sbatch_from_job(script: str) -> str | None:
    """sbatch a script from inside a job: without the job's SLURM_*/SBATCH_* variables, which would otherwise leak into
    the new job's options or environment. Returns the job id, or None (the error is printed)."""
    env = {k: v for k, v in os.environ.items() if not k.startswith(("SLURM_", "SBATCH_", "SRUN_"))}
    out = subprocess.run(["sbatch", "--parsable", script], capture_output=True, text=True, env=env)
    if out.returncode != 0:
        print(f"{_now()} sbatch failed: {(out.stderr or out.stdout).strip()}", flush=True)
        return None
    return out.stdout.strip().split(";")[0]


def _pool_settings(cfg: dict) -> dict:
    """[pool] settings for whole-node workers (submit-workers); cores and mem are required there."""
    p = cfg.get("pool", {})
    missing = [k for k in ("cores", "mem") if k not in p]
    if missing:
        sys.exit(f"[pool] needs {missing} for submit-workers (MUSICA zen4_0768: cores = 192, mem = \"700G\")")
    walltime = str(p.get("walltime", "3-00:00:00"))
    chain_h = float(p.get("chain_after_hours", 24))
    if chain_h * 3600 >= (_elapsed_s(walltime) or 0):
        sys.exit(f"[pool] chain_after_hours ({chain_h:g}) must be shorter than walltime ({walltime})")
    mem_mb = _mem_mb(str(p["mem"]).upper().removesuffix("B"))
    if mem_mb is None:
        sys.exit(f"[pool] mem '{p['mem']}': use e.g. \"700G\"")
    return {"cores": int(p["cores"]), "mem": str(p["mem"]), "mem_mb": mem_mb, "walltime": walltime, "chain_hours": chain_h,
            "workers": int(p.get("workers", 3)), "mem_fraction": float(p.get("mem_fraction", 0.9))}


def work_estimate(cfg: dict, plan: dict, store: "pool.Store", settings: dict) -> None:
    """Print the estimated remaining work in node-hours (memory- and core-bound) and the critical path."""
    specs = pool_specs(plan, list(plan))
    estimator = make_worker(cfg, specs, store, cores=settings["cores"], mem_mb=settings["mem_mb"]).est
    for record in store.results():
        estimator.add(record)
    snap = store.snapshot(specs)
    open_keys = [k for k in plan if snap[k][0] not in (pool.DONE, pool.FAILED)]
    if not open_keys:
        print("No open tasks.")
        return
    est = {k: estimator.estimate(k) for k in plan}
    mem_h = sum(est[k]["mem_mb"] * est[k]["time_s"] for k in open_keys) / (settings["mem_fraction"] * settings["mem_mb"]) / 3600
    core_h = sum(min(specs[k]["cpus"], settings["cores"]) * est[k]["time_s"] for k in open_keys) / settings["cores"] / 3600
    measured_mem = sum(est[k]["mem_src"] != "prior" for k in open_keys)
    measured_time = sum(est[k]["time_src"] != "prior" for k in open_keys)
    critical, kids = {}, {}
    for key, task in plan.items():
        for dep in task["deps"]:
            kids.setdefault(dep, []).append(key)
    for key in reversed(list(plan)):
        critical[key] = (est[key]["time_s"] if key in open_keys else 0) + max((critical[c] for c in kids.get(key, [])), default=0)
    node_h = max(mem_h, core_h)
    print(f"Open tasks: {len(open_keys)} of {len(plan)}; estimates measured for memory {measured_mem}, runtime {measured_time} "
          f"(the rest uses the TOML [resources.*] - their 'time' is a limit, not a runtime, so this is an upper bound)")
    print(f"Estimated work: {node_h:,.0f} node-hours ({'memory' if mem_h >= core_h else 'cores'}-bound; memory {mem_h:,.0f}, "
          f"cores {core_h:,.0f}) on nodes with {settings['cores']} cores / {settings['mem']} x {settings['mem_fraction']:g}")
    print(f"Longest dependency chain: {max(critical.values()) / 3600:,.1f} h (no number of nodes finishes faster)")
    for n in (1, 2, 3, 5, 10):
        print(f"  {n:>2} worker chain(s): ~{max(node_h / n, max(critical.values()) / 3600) / 24:,.1f} days")


def cmd_submit_workers(args) -> None:
    """Submit whole-node worker jobs for the task pool of a config; each chains its own successor."""
    config_path, cfg = _load_config(args.config)
    plan = build_plan(cfg)
    settings = _pool_settings(cfg)
    rdir = RUNS_DIR / cfg["name"]
    if (rdir / "state.json").exists():
        sys.exit(f"'{rdir}' holds a per-task Slurm run (state.json) - use a different run name for the pool")
    pool_root = rdir / "pool"
    # A dry run must not create the pool: estimate from an empty temporary store instead
    store = pool.Store(Path(tempfile.mkdtemp(prefix="mk-dry-pool-")) if args.dry_run and not pool_root.exists() else pool_root)
    if not (pool_root / "meta.json").exists() and not args.dry_run:
        pool._write_json_atomic(pool_root / "meta.json", {"config": str(config_path), "created": _now()})
    work_estimate(cfg, plan, store, settings)
    if args.estimate_only:
        return

    slurm_cfg = cfg["slurm"]
    mail_user = slurm_cfg.get("mail_user") or os.environ.get("MK_MAIL_USER", "")
    # Few long jobs: [pool] mail_type (e.g. BEGIN,END,FAIL) may differ from the per-task [slurm] mail_type
    mail_type = cfg.get("pool", {}).get("mail_type", slurm_cfg.get("mail_type", "FAIL"))
    mail = f"#SBATCH --mail-type={mail_type}\n#SBATCH --mail-user={mail_user}\n" if mail_user else ""
    if not mail_user:
        print("note: no mail address ([slurm] mail_user or $MK_MAIL_USER) - the worker jobs send no mails")
    script = pool_root / "worker.sbatch"
    text = WORKER_SBATCH_TEMPLATE.format(account=slurm_cfg["account"], partition=slurm_cfg["partition"], qos=slurm_cfg.get("qos", slurm_cfg["partition"]),
                                         walltime=settings["walltime"], jobname=f"wrk-{cfg['name']}", jobs_dir=pool_root / "jobs", mail=mail,
                                         name=cfg["name"], chain_hours=settings["chain_hours"], setup=slurm_cfg.get("setup", "").strip(),
                                         repo=slurm_cfg["repo"], config=config_path, cores=settings["cores"], mem=settings["mem"], script=script)
    if args.dry_run:
        print(f"\n--- {script} (dry run: not written) ---\n{text}")
    else:
        script.write_text(text, newline="\n")
    n = args.workers or settings["workers"]
    print(f"\nSubmitting {n} worker chain(s): {settings['walltime']} whole-node jobs, each submitting its successor after "
          f"{settings['chain_hours']:g} h while tasks remain" + ("  (dry run)" if args.dry_run else ""))
    slurm = Slurm(dry_run=args.dry_run)
    for _ in range(n):
        job = slurm.sbatch([str(script)])
        if not args.dry_run:
            store.add_job(job, {"submitted_by": "submit-workers", "script": str(script)})
    print(f"Logs: {pool_root / 'jobs'}/worker_<job>.out; status: cluster.py status {cfg['name']}")


def cmd_local(args) -> None:
    """Run tasks of a config on this machine in dependency order (up to --jobs at once) in a throw-away pool."""
    if args.jobs < 1:
        sys.exit("--jobs must be >= 1")
    _, cfg = _load_config(args.config)
    plan = build_plan(cfg)
    keys = select_keys(plan, args.patterns, args.with_deps)
    cores = os.cpu_count() or 1
    thread_cap = args.threads or max(1, cores // args.jobs)  # parallel slots share the machine's cores
    log_dir = Path(args.log_dir) if args.log_dir else (RUNS_DIR / f"{cfg['name']}-local" / "logs" if args.jobs > 1 else None)
    specs = pool_specs(plan, keys)

    print(f"{len(keys)} task(s) to run locally" + (f", up to {args.jobs} at once" if args.jobs > 1 else "")
          + (f", logs in {log_dir}" if log_dir else "") + ("  (dry run)" if args.dry_run else ""))
    if args.dry_run:
        for i, key in enumerate(keys, 1):
            cmd = [a.replace("@THREADS@", str(min(specs[key]["cpus"], thread_cap, cores))).replace("@NODEDIR@", "<node-dir>") for a in specs[key]["cmd"]]
            print(f"[{i}/{len(keys)}] {key}\n    " + " ".join(cmd))
        return

    total, _ = pool.machine_memory_mb()
    with tempfile.TemporaryDirectory(prefix="mk-local-pool-") as tmp:
        store = pool.Store(Path(tmp), log_dir=log_dir)
        # Memory packing off: -j is the concurrency (the TOML memory is sized for Slurm jobs, not this machine); the
        # memory guard still evicts the newest task if the machine runs out of memory
        worker = make_worker(cfg, specs, store, cores=cores, mem_mb=total or 16 * 1024, mem_packing=False, idle_s=0,
                             max_tasks=args.jobs, thread_cap=thread_cap, keep_going=args.keep_going,
                             console=args.jobs == 1 and log_dir is None, poll_s=2)
        worker.run()
        snap = store.snapshot(specs)
    done = [k for k in keys if snap[k][0] == pool.DONE]
    failed = [k for k in keys if snap[k][0] == pool.FAILED]
    print(f"\n{len(done)} done, {len(failed)} failed, {len(keys) - len(done) - len(failed)} not run")
    for key in failed:
        log = snap[key][2].get("log")
        print(f"  FAILED {key}" + (f"  (log: {log})" if log else ""))
    if failed:
        sys.exit(1)


def load_pool(run: str) -> tuple[Path, "pool.Store", dict, dict] | None:
    """(run dir, store, config, plan) of a pool run, or None if the run is not a pool run."""
    rdir = run_dir(run)
    meta = rdir / "pool" / "meta.json"
    if (rdir / "state.json").exists() or not meta.exists():
        return None
    config = json.loads(meta.read_text())["config"]
    _, cfg = _load_config(config)
    return rdir, pool.Store(rdir / "pool"), cfg, build_plan(cfg)


def pool_status(plan: dict, store: "pool.Store") -> dict:
    """{key: (category, info)} with the categories of `status` (blocked = waits for a failed task)."""
    snap = store.snapshot(plan)
    status = {}
    for key, task in plan.items():  # plan order: parents first
        state, attempt, info = snap[key]
        if state == pool.DONE:
            cat = DONE
        elif state == pool.FAILED:
            cat = FAILED
        elif any(status[d][0] in (FAILED, BLOCKED) for d in task["deps"]):
            cat = BLOCKED
        elif state == pool.RUNNING:
            cat = RUNNING
        else:
            cat = PENDING
        status[key] = (cat, {**info, "attempt": attempt, "state": state})
    return status


def _kind(key: str) -> str:
    return "/".join(key.split("/")[-2:]) if "/c" in key else key.split("/")[-1]  # e.g. 'regret/Markov', 'prepare'


def _print_counts(status: dict) -> None:
    counts = {}
    for key, (cat, _) in status.items():
        counts.setdefault(_kind(key), dict.fromkeys(CATEGORIES, 0))[cat] += 1
    width = max(len(k) for k in counts)
    print(f"{'task':<{width}}  {'total':>6}" + "".join(f"  {c:>8}" for c in CATEGORIES))
    for k, row in counts.items():
        print(f"{k:<{width}}  {sum(row.values()):>6}" + "".join(f"  {row[c] or '':>8}" for c in CATEGORIES))
    totals = {c: sum(r[c] for r in counts.values()) for c in CATEGORIES}
    print(f"{'TOTAL':<{width}}  {len(status):>6}" + "".join(f"  {totals[c]:>8}" for c in CATEGORIES))


def cmd_pool_status(args, rdir: Path, store: "pool.Store", plan: dict) -> None:
    status = pool_status(plan, store)
    _print_counts(status)
    now = time.time()
    workers = store.workers()
    print(f"\nWORKERS ({len(workers)})")
    for wid, w in sorted(workers.items(), key=lambda x: x[1].get("started", "")):
        alive = not w.get("exited") and now - w.get("beat", 0) < pool.STALE_S
        state = "active" if alive else ("exited " + w["exited"] if w.get("exited") else "lost (no heartbeat)")
        size = f"{w['cores']} cores, {w['mem_mb'] / 1024:.0f} GB, started {w.get('started')}" if w.get("cores") else ""
        print(f"  {wid:<40} {state:<28} {len(w.get('running', [])):>3} running  {size}")
    jobs = store.jobs()
    if jobs and shutil.which("squeue"):  # queued / running worker jobs (chained successors included)
        out = subprocess.run(["squeue", "-h", "-j", ",".join(sorted(jobs)), "-o", "%i|%T|%r|%S"], capture_output=True, text=True).stdout
        active = [line.split("|") for line in out.splitlines() if line.count("|") == 3]
        print(f"\nWORKER JOBS: {len(jobs)} submitted, {sum(a[1] == 'RUNNING' for a in active)} running, "
              f"{sum(a[1] == 'PENDING' for a in active)} queued")
        for job, st, reason, start in active:
            print(f"  {job:<12} {st:<10} {reason if st == 'PENDING' else '':<20} {'expected start ' + start if st == 'PENDING' and start != 'N/A' else ''}")
    retries = [r for r in store.results() if r["outcome"] in (pool.EVICTED, pool.INTERRUPTED)]
    if retries:
        print(f"\nRETRIED ATTEMPTS: {sum(r['outcome'] == pool.EVICTED for r in retries)} evicted (memory), "
              f"{sum(r['outcome'] == pool.INTERRUPTED for r in retries)} interrupted (walltime / worker stopped)")
    shown = [args.list] if args.list else [FAILED, BLOCKED]
    for cat in shown:
        keys = [k for k, (c, _) in status.items() if c == cat and (args.filter is None or fnmatch.fnmatch(k, args.filter))]
        if not keys:
            continue
        print(f"\n{cat.upper()} ({len(keys)})")
        if cat == BLOCKED and not args.list:
            roots = {}
            for k in keys:
                stack, seen = list(plan[k]["deps"]), set()
                while stack:
                    d = stack.pop()
                    if d in seen:
                        continue
                    seen.add(d)
                    if status[d][0] == FAILED:
                        roots.setdefault(d, []).append(k)
                    elif status[d][0] == BLOCKED:
                        stack.extend(plan[d]["deps"])
            for root, ks in roots.items():
                print(f"  {len(ks):>4} task(s) waiting for {root}")
            continue
        for k in keys:
            info = status[k][1]
            peak = f"peak {info['peak_rss_mb'] / 1024:.1f} GB" if info.get("peak_rss_mb") else ""
            elapsed = str(datetime.timedelta(seconds=int(info["elapsed_s"]))) if info.get("elapsed_s") is not None else ""
            extra = f"exit {info.get('rc')}" if cat == FAILED else (f"on {info.get('worker')}" if cat == RUNNING else "")
            print(f"  {k:<55} attempt {info['attempt']:<3} {elapsed:>9} {peak:<16} {extra}"
                  + (f"\n      log: {info['log']}" if info.get("log") else ""))
    if not args.list:
        print("\nRetry failed tasks (and unblock the tasks waiting for them): cluster.py restart <run> --failed")


def cmd_pool_restart(args, store: "pool.Store", plan: dict) -> None:
    if args.mem or args.mem_factor or args.cpus or args.time or args.include_pending:
        print("note: --mem/--mem-factor/--cpus/--time/--include-pending do not apply to pool runs (estimates are automatic)")
    status = pool_status(plan, store)
    selected = [k for k, (cat, _) in status.items() if cat == FAILED and (args.failed or any(fnmatch.fnmatch(k, p) for p in args.patterns))]
    if not selected:
        sys.exit("Nothing to restart (only failed tasks can be retried; running workers pick them up again)")
    print(f"Retrying {len(selected)} failed task(s)" + ("  (dry run)" if args.dry_run else ""))
    for key in selected:
        print(f"  {key}")
        if not args.dry_run:
            store.reset(key, status[key][1]["attempt"])


def cmd_cancel(args) -> None:
    pool_run = load_pool(args.run)
    if pool_run:  # all worker jobs incl. queued successors; running tasks are retried by later workers
        jobs = sorted(pool_run[1].jobs())
        print(f"Cancelling {len(jobs)} worker job(s) (finished ones are ignored by scancel)")
        Slurm().scancel(jobs)
        return
    _, state = load_state(args.run)
    jobs = sorted({g["job"] for g in state["groups"].values()} |
                  {a["job"] for t in state["tasks"].values() for a in t["attempts"] if "_" not in a["job"]})
    print(f"Cancelling {len(jobs)} job(s) / array(s)")
    Slurm().scancel(jobs)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("submit", help="Submit all tasks of a config as job arrays with dependencies")
    p.add_argument("config", help="TOML experiment file, e.g. research/MK/experiments/experiment.toml")
    p.add_argument("--dry-run", action="store_true", help="Print the sbatch calls and write the files to runs/<name>-dryrun/ without submitting")
    p.set_defaults(func=cmd_submit)
    p = sub.add_parser("status", help="Task counts per kind and state; lists failed / blocked tasks")
    p.add_argument("run", help="Run name or its TOML file")
    p.add_argument("--list", choices=CATEGORIES, help="List all tasks in this state instead")
    p.add_argument("--filter", help="Only list tasks matching this glob pattern, e.g. 'TX-123BT/*'")
    p.set_defaults(func=cmd_status)
