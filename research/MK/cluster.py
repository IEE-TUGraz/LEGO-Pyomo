def cmd_submit(args) -> None:
    cfg = tomllib.loads(Path(args.config).read_text())
    rdir = RUNS_DIR / cfg["name"]
    if (rdir / "state.json").exists() and not args.dry_run:
        sys.exit(f"'{rdir}' already holds a submitted run - use status/restart, or delete the folder to start over")
    plan = build_plan(cfg)
    groups = group_tasks(plan)
    # NodefileStart limits only the B&B tree: at or above a job's memory limit it can never prevent an OOM of that job
    for dataset in cfg["grid"]["datasets"]:
        name = Path(dataset).name
        nfs = _node_file_start(cfg.get("markov", {}), name)
        mems = sorted({t["res"]["mem"] for t in plan.values() if t["key"].startswith(f"{name}/") and resource_class(t["key"]) != "prepare"
                       and nfs is not None and _mem_mb(t["res"]["mem"].upper().removesuffix("B")) <= nfs * 1024})
        if mems:
            print(f"warning: node_file_start of '{name}' ({nfs:g} GB) is not below the Slurm memory {mems} of some of its solves - "
                  f"node files cannot protect those jobs from running out of memory")

    slurm_cfg = cfg["slurm"]
    nice_step = _nice_step(slurm_cfg.get("nice_step", DEFAULT_NICE_STEP))
    # Mail address from the config or $MK_MAIL_USER (keeps it out of the repo); without one, no mails are requested
    mail_user = slurm_cfg.get("mail_user") or os.environ.get("MK_MAIL_USER", "")
    mail = f"#SBATCH --mail-type={slurm_cfg.get('mail_type', 'FAIL')}\n#SBATCH --mail-user={mail_user}\n" if mail_user else ""
    disk_min_free_gb = int(slurm_cfg.get("disk_min_free_gb", DEFAULT_DISK_MIN_FREE_GB))  # integer: bash arithmetic
    script = SBATCH_TEMPLATE.format(disk_min_free_gb=disk_min_free_gb, account=slurm_cfg["account"], partition=slurm_cfg["partition"], qos=slurm_cfg.get("qos", slurm_cfg["partition"]), mail=mail,
                                    setup=slurm_cfg.get("setup", "").strip(), repo=slurm_cfg["repo"])
    out_dir = rdir if not args.dry_run else rdir.with_name(rdir.name + "-dryrun")
    (out_dir / "logs").mkdir(parents=True, exist_ok=True)
    (out_dir / "commands").mkdir(exist_ok=True)
    (out_dir / "task.sbatch").write_text(script, newline="\n")
    if cfg.get("evaluate", {}).get("output_dir"):
        Path(cfg["evaluate"]["output_dir"]).mkdir(parents=True, exist_ok=True)

    state = {"config": str(Path(args.config).resolve()), "created": _now(), "rundir": str(out_dir.resolve()),
             "mail": bool(mail_user), "nice_step": nice_step, "tasks": {k: {**t, "attempts": []} for k, t in plan.items()}, "groups": {}}
    slurm = Slurm(dry_run=args.dry_run)
    print(f"{len(plan)} tasks in {len(groups)} job arrays")
    for group, members in groups.items():
        cmd_file = out_dir / "commands" / f"{group}.tsv"
        cmd_file.write_text("".join(f"{t['index']}\t{t['key']}\t{t['cmd']}\n" for t in members), newline="\n")
        res = members[0]["res"]
        if group == "evaluate":
            dependency = "afterany:" + ":".join(g["job"] for g in state["groups"].values())
            sbatch_args = ["--export=ALL,TASK_INDEX=1", f"--output={out_dir / 'logs' / 'evaluate_%j.out'}", *(["--mail-type=END,FAIL"] if mail_user else [])]
        else:
            dependency = group_dependency(plan, members)
            if dependency:
                dependency = re.sub(r"@([^:,]+)", lambda m: state["groups"][m.group(1)]["job"], dependency)
            sbatch_args = [f"--array={compress_indices([t['index'] for t in members])}", f"--output={out_dir / 'logs' / (group + '_%A_%a.out')}"]
        job = slurm.sbatch([f"--job-name={members[0]['jobname']}", f"--cpus-per-task={res['cpus']}", f"--mem={res['mem']}",
                            f"--time={res['time']}", f"--nice={nice(members[0], nice_step)}", *sbatch_args, *([f"--dependency={dependency}"] if dependency else []), str(out_dir / "task.sbatch"), str(cmd_file)])
        state["groups"][group] = {"job": job, "cmdfile": str(cmd_file)}
        for t in members:
            task_job, log = (job, out_dir / "logs" / f"evaluate_{job}.out") if group == "evaluate" else \
                (f"{job}_{t['index']}", out_dir / "logs" / f"{group}_{job}_{t['index']}.out")
            state["tasks"][t["key"]]["attempts"].append({"job": task_job, "log": str(log), "res": res, "time": _now()})
        save_state(out_dir, state)  # after every array, so a failed submission can be inspected / cancelled
    print(f"State: {out_dir / 'state.json'}" + ("  (dry run: nothing submitted)" if args.dry_run else ""))


def cmd_status(args) -> None:
    pool_run = load_pool(args.run)
    if pool_run:
        return cmd_pool_status(args, pool_run[0], pool_run[1], pool_run[3])
    rdir, state = load_state(args.run)
    status = classify(state, Slurm.query({current_job(t) for t in state["tasks"].values() if current_job(t)}))

    def kind(key):
        return "/".join(key.split("/")[-2:]) if "/c" in key else key.split("/")[-1]  # e.g. 'regret/Markov', 'prepare'

    counts = {}
    for key, (cat, _) in status.items():
        counts.setdefault(kind(key), dict.fromkeys(CATEGORIES, 0))[cat] += 1
    width = max(len(k) for k in counts)
    print(f"{'task':<{width}}  {'total':>6}" + "".join(f"  {c:>8}" for c in CATEGORIES))
    for k, row in counts.items():
        print(f"{k:<{width}}  {sum(row.values()):>6}" + "".join(f"  {row[c] or '':>8}" for c in CATEGORIES))
    totals = {c: sum(r[c] for r in counts.values()) for c in CATEGORIES}
    print(f"{'TOTAL':<{width}}  {len(status):>6}" + "".join(f"  {totals[c]:>8}" for c in CATEGORIES))

    def line(key, entry):
        task = state["tasks"][key]
        rss = entry.get("maxrss_mb")
        mem = f"mem {_fmt_mem(rss)}/{task['attempts'][-1]['res']['mem']}" if rss else ""
        return (f"  {key:<55} {entry.get('state', '?'):<14} exit {entry.get('exit', '-'):<6} {entry.get('elapsed', ''):>11} {mem:<16}"
                f" job {current_job(task)}  (attempt {len(task['attempts'])})\n      log: {task['attempts'][-1]['log']}")

    shown = [args.list] if args.list else [FAILED, BLOCKED, UNKNOWN]
    for cat in shown:
        keys = [k for k, (c, _) in status.items() if c == cat and (args.filter is None or fnmatch.fnmatch(k, args.filter))]
        if not keys:
            continue
        print(f"\n{cat.upper()} ({len(keys)})")
        if cat == BLOCKED and not args.list:  # group by the failed task they wait for
            by_root = {}
            for k in keys:
                for root in failed_ancestors(state, status, k) or ["(unknown)"]:
                    by_root.setdefault(root, []).append(k)
            for root, ks in by_root.items():
                print(f"  {len(ks):>4} task(s) waiting for {root}")
        else:
            for k in keys:
                print(line(k, status[k][1]))
    if not args.list:
        print("\nRestart failed tasks (and the tasks waiting for them): cluster.py restart <run> --failed [--mem-factor 1.5]")


def cmd_restart(args) -> None:
    pool_run = load_pool(args.run)
    if pool_run:
        return cmd_pool_restart(args, pool_run[1], pool_run[3])
    rdir, state = load_state(args.run)
    tasks = state["tasks"]
    status = classify(state, Slurm.query({current_job(t) for t in tasks.values() if current_job(t)}))
    restartable = {FAILED, BLOCKED, UNKNOWN} | ({PENDING} if args.include_pending else set())

    selected = [k for k in tasks if k != "evaluate" and status[k][0] in restartable and
                ((args.failed and status[k][0] == FAILED) or any(fnmatch.fnmatch(k, p) for p in args.patterns))]
    skipped = [k for k in tasks if any(fnmatch.fnmatch(k, p) for p in args.patterns) and k not in selected and k != "evaluate"]
    if skipped:
        print(f"Not restarting {len(skipped)} matching task(s) that are {sorted({status[k][0] for k in skipped})} "
              f"(done runs are skipped by --no-overwrite anyway; delete the .sqlite to recompute; queued ones need --include-pending)")
    if not selected:
        sys.exit("Nothing to restart")
    # Everything downstream that has not finished must be resubmitted too: its old jobs wait for the old (failed) ones
    follow = [k for k in descendants(state, set(selected)) if status[k][0] in {PENDING, BLOCKED, FAILED, UNKNOWN}]
    resubmit = [k for k in tasks if k in set(selected) | set(follow)]  # plan order = dependency order
    print(f"Restarting {len(selected)} task(s) + {len(follow)} dependent task(s)")
    if args.cpus:
        print(f"  warning: --cpus {args.cpus} makes the work units / solver times of the restarted tasks incomparable to the other "
              f"solves of their dataset (prefer --mem / --time)")

    slurm = Slurm(dry_run=args.dry_run)
    nice_step = state.get("nice_step", DEFAULT_NICE_STEP)
    slurm.scancel([current_job(tasks[k]) for k in resubmit if status[k][0] in {PENDING, BLOCKED}])
    new_jobs = {}
    for key in resubmit:
        task = tasks[key]
        res = dict(task["attempts"][-1]["res"])
        if key in selected:
            if args.mem:
                res["mem"] = args.mem
            elif args.mem_factor:
                res["mem"] = _scale_mem(res["mem"], args.mem_factor)
            if args.cpus:
                res["cpus"] = args.cpus
            if args.time:
                res["time"] = args.time
        deps = []
        for dep in task["deps"]:
            if dep in new_jobs:
                deps.append(new_jobs[dep])
            elif status[dep][0] != DONE:
                if status[dep][0] not in {RUNNING, PENDING}:
                    print(f"  warning: {key} depends on {dep} ({status[dep][0]}), which is not restarted - it will not start")
                deps.append(current_job(tasks[dep]))
        group = task["group"]
        job = slurm.sbatch([f"--job-name={task.get('jobname', group)}", f"--cpus-per-task={res['cpus']}", f"--mem={res['mem']}",
                            f"--time={res['time']}", f"--nice={nice(task, nice_step)}", f"--export=ALL,TASK_INDEX={task['index']}", f"--output={Path(state['rundir']) / 'logs' / (group + '_%j.out')}",
                            *([f"--dependency=afterok:{':'.join(deps)}"] if deps else []),
                            str(Path(state["rundir"]) / "task.sbatch"), state["groups"][group]["cmdfile"]])
        new_jobs[key] = job
        task["attempts"].append({"job": job, "log": str(Path(state["rundir"]) / "logs" / f"{group}_{job}.out"), "res": res, "time": _now()})

    # Evaluation must wait for the new jobs too
    if "evaluate" in tasks and status["evaluate"][0] not in {DONE, RUNNING}:
        if status["evaluate"][0] in {PENDING, BLOCKED}:
            slurm.scancel([current_job(tasks["evaluate"])])
        active = [current_job(t) for k, t in tasks.items() if k != "evaluate" and (k in new_jobs or status[k][0] in {PENDING, RUNNING})]
        active = sorted({j.split("_")[0] if "_" in j else j for j in active})
        ev = tasks["evaluate"]
        res = ev["attempts"][-1]["res"]
        job = slurm.sbatch(["--job-name=evaluate", f"--cpus-per-task={res['cpus']}", f"--mem={res['mem']}", f"--time={res['time']}",
                            "--export=ALL,TASK_INDEX=1", f"--output={Path(state['rundir']) / 'logs' / 'evaluate_%j.out'}", *(["--mail-type=END,FAIL"] if state.get("mail", True) else []),
                            *([f"--dependency=afterany:{':'.join(active)}"] if active else []),
                            str(Path(state["rundir"]) / "task.sbatch"), state["groups"]["evaluate"]["cmdfile"]])
        ev["attempts"].append({"job": job, "log": str(Path(state["rundir"]) / "logs" / f"evaluate_{job}.out"), "res": res, "time": _now()})
    if not args.dry_run:
        save_state(rdir, state)


def _elapsed_s(value: str) -> int | None:
    """Slurm elapsed '[D-]HH:MM:SS' / 'MM:SS' -> seconds."""
    m = re.fullmatch(r"(?:(\d+)-)?(?:(\d+):)?(\d+):(\d+)", value.strip())
    if not m:
        return None
    d, h, mi, s = (int(x) if x else 0 for x in m.groups())
    return ((d * 24 + h) * 60 + mi) * 60 + s


def _fmt_time(seconds: float) -> str:
    """Seconds -> Slurm time '[D-]HH:MM:SS'."""
    seconds = int(seconds)
    d, rest = divmod(seconds, 86400)
    return (f"{d}-" if d else "") + f"{rest // 3600:02d}:{rest % 3600 // 60:02d}:{rest % 60:02d}"


def resource_class(key: str) -> str:
    """[resources.*] class of a task key (same rule as build_plan)."""
    parts = key.split("/")
    if key == "evaluate" or parts[-1] in ("prepare", "truth-original"):
        return parts[-1]
    task, edge = parts[-2], parts[-1]
    return "rp" if task in ("main", "operational") and edge != "Truth" else "full"


def cmd_resources(args) -> None:
    """Measured peak memory / runtime per (dataset, resource class) and suggested [resources.*] values. Slurm runs: from
    sacct (`--save` writes runs/<run>/measurements.json, which pool runs use as seed); pool runs: from the pool results."""
    groups = {}  # (dataset, class) -> {"done": [(key, rss_mb, elapsed_s, requested)], "limit": [(key, what, limit)], "open": n}

    def group(key):
        dataset = key.split("/")[0] if key != "evaluate" else "evaluate"
        return groups.setdefault((dataset, resource_class(key)), {"done": [], "limit": [], "open": 0})

    pool_run = load_pool(args.run)
    if pool_run:
        rdir, store, _, plan = pool_run
        status = pool_status(plan, store)
        for record in store.results():
            est = record.get("estimate") or {}
            requested = {"mem": _fmt_mem(est["mem_mb"]) if est.get("mem_mb") else "?", "time": _fmt_time(est["time_s"]) if est.get("time_s") else "?"}
            if record["key"] not in plan:
                continue
            if record["outcome"] == pool.DONE and record.get("noop"):
                continue  # had nothing to do (output existed): no measurement
            if record["outcome"] == pool.DONE:
                group(record["key"])["done"].append((record["key"], record.get("peak_rss_mb"), record.get("elapsed_s"), requested))
            elif record["outcome"] == pool.EVICTED:
                group(record["key"])["limit"].append((record["key"], "evicted", _fmt_mem(record.get("peak_rss_mb") or 0)))
            elif record["outcome"] == pool.INTERRUPTED:
                group(record["key"])["limit"].append((record["key"], "interrupted", _fmt_time(record.get("elapsed_s") or 0)))
        for key, (cat, _) in status.items():
            if cat in (PENDING, RUNNING, BLOCKED):
                group(key)["open"] += 1
        print("Source: pool results ('requested' = the estimate the attempt started with; evicted = memory ran out, "
              "interrupted = walltime ended)")
    else:
        rdir, state = load_state(args.run)
        status = classify(state, Slurm.query({current_job(t) for t in state["tasks"].values() if current_job(t)}))
        measurements = []
        for key, (cat, entry) in status.items():
            res = state["tasks"][key]["attempts"][-1]["res"]
            rss, elapsed = entry.get("maxrss_mb"), _elapsed_s(entry.get("elapsed", ""))
            if cat == DONE and pool._log_has_marker(Path(state["tasks"][key]["attempts"][-1]["log"]), pool.NOOP_MARKER):
                continue  # had nothing to do (output existed): no measurement
            if cat == DONE:
                group(key)["done"].append((key, rss, elapsed, res))
                measurements.append({"key": key, "outcome": pool.DONE, "peak_rss_mb": rss, "elapsed_s": elapsed, "job": current_job(state["tasks"][key])})
            elif cat == FAILED and entry.get("state") in ("OUT_OF_MEMORY", "TIMEOUT"):
                oom = entry["state"] == "OUT_OF_MEMORY"  # hit a limit: the true need is above the request
                group(key)["limit"].append((key, entry["state"], res["mem"] if oom else res["time"]))
                measurements.append({"key": key, "outcome": "oom" if oom else "timeout", "peak_rss_mb": rss, "elapsed_s": elapsed,
                                     "limit_mb": _mem_mb(res["mem"].upper().removesuffix("B")), "limit_s": _elapsed_s(res["time"]),
                                     "job": current_job(state["tasks"][key])})
            elif cat in (PENDING, RUNNING, BLOCKED, UNKNOWN):
                group(key)["open"] += 1
        if args.save:
            (rdir / "measurements.json").write_text(json.dumps(measurements, indent=1))
            print(f"Saved {len(measurements)} measurement(s) to {rdir / 'measurements.json'} (seed for pool runs: [pool] seed_runs)\n")

    print(f"Suggestions: mem = {args.mem_factor:g} x max peak, time = {args.time_factor:g} x max elapsed "
          f"(min {_fmt_time(args.min_time * 60)}); based on finished tasks only\n")
    head = f"{'dataset':<10} {'class':<15} {'done':>4} {'open':>4}  {'max peak':>9} {'requested':>9} {'-> mem':>7}   {'max elapsed':>11} {'requested':>11} {'-> time':>11}  peak / longest task"
    print(head)
    print("-" * len(head))
    for (dataset, cls), g in sorted(groups.items(), key=lambda x: (x[0][0] == "evaluate", x[0][0], x[0][1])):
        done = g["done"]
        if not done:
            print(f"{dataset:<10} {cls:<15} {0:>4} {g['open']:>4}  (nothing finished yet)")
        else:
            with_rss = [d for d in done if d[1] is not None]
            with_time = [d for d in done if d[2] is not None]
            peak = max(with_rss, key=lambda d: d[1]) if with_rss else None
            longest = max(with_time, key=lambda d: d[2]) if with_time else None
            mem_s = f"{_fmt_mem(peak[1]):>9} {peak[3]['mem']:>9} {_fmt_mem(max(peak[1] * args.mem_factor, 1024)):>7}" if peak else f"{'?':>9} {'':>9} {'':>7}"
            time_s = f"{_fmt_time(longest[2]):>11} {longest[3]['time']:>11} {_fmt_time(max(longest[2] * args.time_factor, args.min_time * 60)):>11}" if longest else f"{'?':>11} {'':>11} {'':>11}"
            names = " / ".join(dict.fromkeys(d[0].removeprefix(f"{dataset}/") for d in (peak, longest) if d))
            print(f"{dataset:<10} {cls:<15} {len(done):>4} {g['open']:>4}  {mem_s}   {time_s}  {names}")
        for key, st, limit in g["limit"]:
            print(f"{'':<10} {'':<15} !! {key.removeprefix(f'{dataset}/')}: {st} at {limit} - "
                  + (f"this class needs more than {limit}" if st in ("OUT_OF_MEMORY", "TIMEOUT") else "retried (lower bound for the estimate)"))
    print("\nSet these per dataset in [resources.<class>] of the full experiment's TOML. The pilot covers only its grid points "
          "(largest RP models); solve times vary more across demand levels / TMs than memory - keep a margin on time.")


def cmd_prioritize(args) -> None:
    rdir, state = load_state(args.run)
    if args.nice_step is not None:
        state["nice_step"] = _nice_step(args.nice_step)  # also used by later restarts
    status = classify(state, Slurm.query({current_job(t) for t in state["tasks"].values() if current_job(t)}))
    prioritize(state, [k for k in state["tasks"] if k != "evaluate" and status[k][0] == PENDING], Slurm(dry_run=args.dry_run))
    if args.nice_step is not None and not args.dry_run:
        save_state(rdir, state)


def cmd_log(args) -> None:
    _, state = load_state(args.run)
    matches = [k for k in state["tasks"] if fnmatch.fnmatch(k, args.key)]
    if len(matches) != 1:
        sys.exit(f"'{args.key}' matches {len(matches)} tasks" + (f": {matches[:10]}" if matches else ""))
    task = state["tasks"][matches[0]]
    for attempt in task["attempts"]:
        print(f"attempt job {attempt['job']} ({attempt['time']}, {attempt['res']}): {attempt['log']}")
    log = Path(task["attempts"][-1]["log"])
    if log.exists():
        print(f"\n--- last {args.lines} lines of {log} ---")
        print("\n".join(log.read_text(errors="replace").splitlines()[-args.lines:]))
    else:
        print("(log does not exist yet)")


